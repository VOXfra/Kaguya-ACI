def compute_keys(cid,passcode,use_sha3):
    h=(lambda b:hashlib.sha3_256(b).digest()) if use_sha3 else (lambda b:hashlib.sha256(b).digest())
    return h(h((1).to_bytes(4,'big'))+h(cid.encode('ascii').ljust(48,b'\0'))+passcode.encode('ascii'))

def derive_image_keys(ek,seed):
    base=hmac.new(ek,seed,hashlib.sha256).digest()
    enc=hmac.new(base,struct.pack('<I',1)+seed,hashlib.sha256).digest()
    return enc[:16],enc[16:]

